export function publicSearchQuery(value) {
  if (typeof value !== 'string') return '';
  const query = value.trim().split(/\s+/).filter(word => !/^(?:梗|来历|含义|出处|意思|用法|百科|是什么|什么梗)$/.test(word)).join(' ').slice(0, 41);
  if (query.length < 2 || query.length > 40 || /https?:|@|\d{5,}|密码|手机号|身份证|我叫|家住|API.?key|密钥/i.test(query)) return '';
  return query;
}
